"""Read-only source/pin audit; retain generated sidecars without cleanup."""
from pathlib import Path
from datetime import datetime, timezone
import hashlib, json, shutil

ROOT = Path(__file__).resolve().parents[3]
HERE = Path(__file__).resolve().parent
OUT = HERE / "freeze-02"
OUT.mkdir(exist_ok=False)
def sha(path): return hashlib.sha256(path.read_bytes()).hexdigest()
owned = ["chapter1/view/cloister_actors.gd", "chapter1/view/cloister_effects.gd", "chapter1/view/hero_occlusion_rim.gdshader", "chapter1/presentation/combat_audio.gd"]
manifest = {}
for rel in owned:
    path = ROOT / rel
    dst = OUT / "source" / rel
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(path, dst)
    manifest[rel] = {"sha256": sha(path), "bytes": path.stat().st_size, "copy_sha256": sha(dst)}
(OUT / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
before = json.loads((HERE / "before-manifest.json").read_text(encoding="utf-8-sig"))
before_audit = {rel: {"expected": wanted, "copy": sha(HERE/"before"/rel), "current": sha(ROOT/rel)} for rel,wanted in before.items()}
(OUT / "before-audit.json").write_text(json.dumps(before_audit, indent=2), encoding="utf-8")
# Preserve a bounded time-window inventory. We lack a pre-command sidecar
# inventory, so creation/mtime are evidence of candidates, not proof of origin.
start = datetime(2026,10,31,23,54,0,tzinfo=timezone.utc).timestamp()
end = datetime(2026,10,31,23,56,0,tzinfo=timezone.utc).timestamp()
candidates = []
for path in list(ROOT.rglob("*")):
    if HERE in path.parents: continue
    if not path.is_file() or ".godot" in path.parts: continue
    if path.suffix not in [".import", ".uid"]: continue
    stat = path.stat()
    if not (start<=stat.st_ctime<=end or start<=stat.st_mtime<=end): continue
    rel = path.relative_to(ROOT)
    dst = OUT / "import-sidecar-candidates" / (hashlib.sha256(str(rel).encode()).hexdigest()+path.suffix)
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(path,dst)
    candidates.append({"path":str(rel).replace("\\","/"),"bytes":stat.st_size,"sha256":sha(path),"creation_utc":datetime.fromtimestamp(stat.st_ctime,timezone.utc).isoformat(),"mtime_utc":datetime.fromtimestamp(stat.st_mtime,timezone.utc).isoformat()})
note = {"command":[r"C:\Project\rea-tools\godot-4.5.1\Godot_v4.5.1-stable_win64_console.exe","--headless","--path",".","--editor","--import","--quit"],
        "actual_exit":0,"raw_log":"No file capture configured; tool output only (initial output truncated). Full raw log unavailable.",
        "window_utc":[datetime.fromtimestamp(start,timezone.utc).isoformat(),datetime.fromtimestamp(end,timezone.utc).isoformat()],
        "scope":"Candidate .import/.uid outside .godot with creation or mtime in window. No pre-command inventory; no certainty all were generated by this command. Cache files excluded. No original or sidecar deleted.",
        "candidate_count":len(candidates),"candidates":candidates}
(OUT / "import-incident.json").write_text(json.dumps(note,indent=2),encoding="utf-8")
global_before = json.loads(Path(r"C:\Project\game-research\implementation-backups\chapter1-quality04-before-20261101-01\manifest.json").read_text(encoding="utf-8-sig"))
png_pins = []
for rel,record in global_before["files"].items():
    if not rel.endswith(".png"):continue
    path=ROOT/rel
    png_pins.append({"path":rel,"expected":record["sha256"],"current":sha(path),"equal":record["sha256"].lower()==sha(path)})
(OUT / "original-png-pins.json").write_text(json.dumps({"count":len(png_pins),"mismatches":[r for r in png_pins if not r["equal"]],"records":png_pins},indent=2),encoding="utf-8")
print(json.dumps({"owned_files":len(manifest),"before_copy_mismatches":[r for r,v in before_audit.items() if v["copy"]!=v["expected"]],"png_pins":len(png_pins),"png_mismatches":[r for r in png_pins if not r["equal"]],"sidecar_candidates":len(candidates)}))
