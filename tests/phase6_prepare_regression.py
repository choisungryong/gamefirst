"""Prepare output-only legacy test copies and immutable phase6 safety guards.

No Godot process or historical fixture generator is run here. Existing reports,
goldens, test sources and the real phase5 user save are read-only guard targets.
"""
from pathlib import Path
import hashlib
import json

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "evidence/phase6/verification"
USER_SAVE = Path(r"C:\Users\twins\AppData\Roaming\Godot\app_userdata\D2R Combat Baseline\equipment-v1.json")
EXPECTED_USER_SHA = "b376f88d6db4c443332908f5cf09860a4eda24701cbefb25c9cbd8289e202353"
RECIPES = [
    ("phase2_scene_independent.gd", "res://evidence/phase3/verification/scene-regression-report", "res://evidence/phase6/verification/legacy-scene-regression-report", 1),
    ("phase3_scene_independent.gd", "res://evidence/phase3/verification/mixed-corpse-report", "res://evidence/phase6/verification/legacy-mixed-corpse-report", 1),
    ("phase5_sim_storage.gd", "res://evidence/phase5/verification/", "res://evidence/phase6/verification/", 2),
    ("phase5_scene.gd", "res://evidence/phase5/verification/", "res://evidence/phase6/verification/", 1),
    ("test_converter.py", "ROOT / 'evidence' / 'phase1'", "ROOT / 'evidence' / 'phase6' / 'verification'", 2),
]


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def guard(path, kind):
    return {"path": str(path), "kind": kind, "exists": path.exists(), "sha256": sha(path) if path.is_file() else None, "size": path.stat().st_size if path.is_file() else None}


def verify_guards(entries):
    result = []
    for before in entries:
        after = guard(Path(before["path"]), before["kind"])
        result.append({**before, "after": after, "unchanged": after == before})
    return result


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    if not USER_SAVE.is_file() or sha(USER_SAVE) != EXPECTED_USER_SHA:
        raise RuntimeError("The real phase5 native save differs from the parent pin; preserve it and ask the parent before tests")
    copies = []
    for name, old, new, count in RECIPES:
        source = ROOT / "tests" / name
        destination = ROOT / "tests" / ("phase6_regression_" + name)
        original = source.read_text(encoding="utf-8")
        assert original.count(old) == count, (name, original.count(old), count)
        expected = original.replace(old, new)
        if destination.exists():
            assert destination.read_text(encoding="utf-8") == expected, "Refusing to overwrite differing regression copy"
        else:
            destination.write_text(expected, encoding="utf-8", newline="")
        assert destination.read_text(encoding="utf-8").replace(new, old) == original
        copies.append({"source": str(source), "source_sha256": sha(source), "copy": str(destination), "copy_sha256": sha(destination), "only_replacement": {"from": old, "to": new, "count": count}})
    manifest = OUT / "legacy-safe-copy-manifest.json"
    if manifest.exists():
        prior = json.loads(manifest.read_text(encoding="utf-8"))
        assert prior["copies"] == copies, "Prior output-only source copies changed"
        checked = verify_guards(prior["guards"])
        assert all(row["unchanged"] for row in checked), "A historical guard changed; investigate before running tests"
        guards = prior["guards"]
    else:
        targets = {}
        for phase in ("phase3", "phase4", "phase5"):
            for name in ("scene-run.json", "qa-report.json", "summary.json", "verification-summary.json"):
                for path in (ROOT / "evidence" / phase).rglob(name):
                    targets[path] = "historical report (current bytes, not recovery of earlier overwritten reports)"
        for path in (ROOT / "tests/fixtures").glob("*.json"):
            targets[path] = "historical fixture; never regenerated by phase6 tests"
        for name in ("audit_phase4_runs.py", "test_phase4_audit.py", "audit_phase5_runs.py", "test_phase5_audit.py"):
            targets[ROOT / "tests" / name] = "historical auditor source"
        targets[USER_SAVE] = "real phase5 native user save; no test writes"
        guards = [guard(path, targets[path]) for path in sorted(targets, key=str)]
        record = {"scope": "Output literals only; current historical reports/fixtures/auditors and the real user save are guarded, not regenerated", "copies": copies, "guards": guards}
        manifest.write_text(json.dumps(record, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"copies": len(copies), "guarded_files": len(guards), "user_save_sha256": sha(USER_SAVE), "success": True}))


if __name__ == "__main__":
    main()
